#!/usr/bin/env bash
set -euo pipefail
umask 077

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
usage() {
    printf 'Usage: %s STATE_DIR\n' "$0" >&2
    exit 2
}
fail() {
    printf 'Offline dependency installation failed: %s\n' "$1" >&2
    exit 1
}

[[ $# == 1 ]] || usage
[[ $EUID -ne 0 ]] || fail 'run as an unprivileged workstation user, never root'
for command in ssh tar sha256sum realpath stat tr; do
    command -v "$command" >/dev/null 2>&1 || fail "missing required host command: $command"
done
[[ -x /usr/bin/ssh ]] || fail 'OpenSSH client is unavailable at /usr/bin/ssh'
[[ -d "$1" && ! -L "$1" ]] || fail 'STATE_DIR must be a real directory, not a symlink'
state_dir=$(realpath -e -- "$1") || fail 'STATE_DIR does not exist'
case "$state_dir" in
    /tmp/dorothy-traefik-acceptance.*) ;;
    *) fail 'STATE_DIR is outside the private acceptance state root' ;;
esac
[[ -f "$state_dir/.owner" && ! -L "$state_dir/.owner" && -O "$state_dir/.owner" && -O "$state_dir" ]] || fail 'STATE_DIR has no private regular ownership marker'
[[ "$(stat -c '%a' -- "$state_dir")" == 700 ]] || fail 'STATE_DIR must be private (mode 0700)'
[[ "$(<"$state_dir/.owner")" == dorothy-traefik-acceptance-owned-state-v1 ]] || fail 'STATE_DIR ownership marker does not match'
bash "$script_dir/guest-barrier-check.sh" precondition "$state_dir"

bundle="$state_dir/offline-deps"
[[ -d "$bundle" && ! -L "$bundle" && -f "$bundle/.ready" && ! -L "$bundle/.ready" ]] || fail 'offline dependencies are not staged in STATE_DIR'
[[ -f "$bundle/manifest.tsv" && ! -L "$bundle/manifest.tsv" && -f "$bundle/SHA256SUMS" && ! -L "$bundle/SHA256SUMS" ]] || fail 'offline dependency manifest or checksums are missing'
mapfile -t ready < "$bundle/.ready"
[[ ${#ready[@]} == 2 && "${ready[0]}" == dorothy-offline-deps-ready-v1 ]] || fail 'offline dependency ready marker is malformed'
actual_sums=$(sha256sum "$bundle/SHA256SUMS")
actual_sums=${actual_sums%% *}
[[ "$actual_sums" == "${ready[1]}" ]] || fail 'offline dependency ready marker does not match its checksum file'
(cd "$bundle" && sha256sum --check --strict --status SHA256SUMS) || fail 'offline dependency artifacts failed checksum verification'

[[ -f "$state_dir/handle.env" && ! -L "$state_dir/handle.env" ]] || fail 'owned SSH management handle is missing'
[[ -f "$state_dir/ssh_config" && ! -L "$state_dir/ssh_config" ]] || fail 'owned SSH configuration is missing'
[[ -f "$state_dir/known_hosts" && ! -L "$state_dir/known_hosts" && -s "$state_dir/known_hosts" ]] || fail 'owned SSH host-key file is missing'
[[ -f "$state_dir/id_ed25519" && ! -L "$state_dir/id_ed25519" ]] || fail 'owned SSH identity is missing'
[[ -f "$state_dir/qemu.pid" && ! -L "$state_dir/qemu.pid" ]] || fail 'owned guest QEMU pid file is missing'

unset STATE_DIR SSH_HOST SSH_PORT SSH_USER SSH_IDENTITY SSH_CONFIG QEMU_PID_FILE
# Generated by prepare.sh inside the private, ownership-marked state directory.
# shellcheck disable=SC1090
source "$state_dir/handle.env"
[[ "${STATE_DIR:-}" == "$state_dir" && "${SSH_HOST:-}" == 127.0.0.1 && "${SSH_USER:-}" == root ]] || fail 'SSH handle does not identify the owned local root guest'
[[ "${SSH_CONFIG:-}" == "$state_dir/ssh_config" && "${SSH_IDENTITY:-}" == "$state_dir/id_ed25519" ]] || fail 'SSH handle paths do not match the private state directory'
[[ "${QEMU_PID_FILE:-}" == "$state_dir/qemu.pid" && "${SSH_PORT:-}" =~ ^[0-9]{1,5}$ ]] || fail 'SSH handle has invalid guest ownership or port data'
(( 10#$SSH_PORT >= 1 && 10#$SSH_PORT <= 65535 )) || fail 'SSH management port is out of range'

pid=$(<"$state_dir/qemu.pid")
[[ "$pid" =~ ^[0-9]+$ ]] || fail 'owned guest QEMU pid is invalid'
kill -0 "$pid" 2>/dev/null || fail 'owned guest QEMU process is not running'
[[ -r "/proc/$pid/cmdline" ]] || fail 'cannot verify the owned guest QEMU command line'
command_line=$(tr '\0' ' ' < "/proc/$pid/cmdline")
[[ "$command_line" == *qemu-system-x86_64* && "$command_line" == *"$state_dir/guest.qcow2"* ]] || fail 'QEMU pid does not own the private acceptance guest image'

expected_sums=${ready[1]}
# Stage ICU but leave its actual installation to the provider prerequisite under test.
mapfile -t packages < <(awk -F '\t' '$1 == "package" && $2 != "archive" && $4 != "libicu76" { print $4 }' "$bundle/manifest.tsv")
((${#packages[@]} > 0)) || fail 'offline dependency manifest contains no package closure'
for package in "${packages[@]}"; do
    [[ "$package" =~ ^[a-z0-9][a-z0-9+.-]*$ ]] || fail 'offline dependency manifest contains an unsafe package name'
done

remote_program=$(cat <<'REMOTE'
set -euo pipefail
expected=$1
shift
packages=("$@")
[[ "$expected" =~ ^[0-9a-f]{64}$ && ${#packages[@]} -gt 0 ]]
incoming=/var/lib/.dorothy-offline-deps-staging
repository=/var/lib/dorothy-offline-deps
umask 077
[[ ! -e "$incoming" && ! -L "$incoming" ]] || { echo 'refusing an existing incomplete guest package transfer' >&2; exit 1; }
mkdir -m 700 "$incoming"
trap 'rm -rf -- "$incoming"' EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM
tar --extract --file - --directory "$incoming" --no-same-owner --no-same-permissions
[[ -f "$incoming/SHA256SUMS" && ! -L "$incoming/SHA256SUMS" ]]
actual=$(sha256sum "$incoming/SHA256SUMS")
actual=${actual%% *}
[[ "$actual" == "$expected" ]]
(cd "$incoming" && sha256sum --check --strict --status SHA256SUMS)
[[ -f "$incoming/manifest.tsv" && ! -L "$incoming/manifest.tsv" ]]
[[ -d "$incoming/repo/pool" && ! -L "$incoming/repo/pool" ]]
if [[ -e "$repository" || -L "$repository" ]]; then
    [[ -d "$repository" && ! -L "$repository" && -f "$repository/SHA256SUMS" && ! -L "$repository/SHA256SUMS" ]]
    installed_sums=$(sha256sum "$repository/SHA256SUMS")
    installed_sums=${installed_sums%% *}
    [[ "$installed_sums" == "$expected" ]]
    (cd "$repository" && sha256sum --check --strict --status SHA256SUMS)
    rm -rf -- "$incoming"
else
    mv -- "$incoming" "$repository"
fi
trap - EXIT HUP INT TERM

mkdir -p /var/cache/apt/archives/partial /etc/apt/sources.list.d
shopt -s dotglob nullglob
apt_sources=(/etc/apt/sources.list.d/*)
for apt_source in "${apt_sources[@]}"; do
    rm -rf -- "$apt_source"
done
shopt -u dotglob nullglob
rm -f -- /etc/apt/sources.list
printf 'deb [arch=amd64 trusted=yes] file:/var/lib/dorothy-offline-deps/repo ./\n' > /etc/apt/sources.list
chmod 644 /etc/apt/sources.list

shopt -s nullglob
archives=("$repository"/repo/pool/*.deb)
shopt -u nullglob
((${#archives[@]} > 0))
cp --remove-destination "${archives[@]}" /var/cache/apt/archives/
chmod 755 "$repository" "$repository/repo" "$repository/repo/pool"
chmod 644 "$repository/manifest.tsv" "$repository/SHA256SUMS" "${archives[@]}"

packages_index="$repository/repo/Packages.new"
: > "$packages_index"
manifest_package_count=0
while IFS=$'\t' read -r kind archive pool_path package version architecture size expected_sha filename _; do
    [[ "$kind" == package && "$archive" != archive ]] || continue
    deb="$repository/repo/pool/$filename"
    [[ -f "$deb" && ! -L "$deb" ]] || { echo "manifest package is missing: $filename" >&2; exit 1; }
    actual_size=$(stat -c '%s' -- "$deb")
    actual_sha=$(sha256sum "$deb")
    actual_sha=${actual_sha%% *}
    [[ "$actual_size" == "$size" && "$actual_sha" == "$expected_sha" ]] || {
        echo "manifest digest or size mismatch: $filename" >&2
        exit 1
    }
    control=$(dpkg-deb --field "$deb")
    identity=$(printf '%s\n' "$control" | awk -F ': ' '
        $1 == "Package" { package=$2 }
        $1 == "Version" { version=$2 }
        $1 == "Architecture" { architecture=$2 }
        END { printf "%s\t%s\t%s", package, version, architecture }
    ')
    [[ "$identity" == "$package"$'\t'"$version"$'\t'"$architecture" ]] || {
        echo "manifest package identity mismatch: $filename" >&2
        exit 1
    }
    local_filename=${deb#"$repository/repo/"}
    printf '%s\nFilename: %s\nSize: %s\nSHA256: %s\n\n' \
        "$control" "$local_filename" "$size" "$expected_sha" >> "$packages_index"
    manifest_package_count=$((manifest_package_count + 1))
done < "$repository/manifest.tsv"
((manifest_package_count == 109))
chmod 644 "$packages_index"
mv -- "$packages_index" "$repository/repo/Packages"
chmod 644 "$repository/repo/Packages"

apt_options=(
    -o Dir::Etc::sourcelist=/etc/apt/sources.list
    -o Dir::Etc::sourceparts=-
    -o Acquire::Check-Valid-Until=false
    -o Acquire::Retries=0
    -o Acquire::Languages=none
)
apt-get "${apt_options[@]}" update
policy_path=/usr/sbin/policy-rc.d
policy_contents=$'#!/bin/sh\nexit 101\n'
policy_hash=$(printf '%s' "$policy_contents" | sha256sum)
policy_hash=${policy_hash%% *}
policy_owned=1
remove_policy() {
    if (( policy_owned )); then
        [[ -f "$policy_path" && ! -L "$policy_path" ]] || {
            echo 'created policy-rc.d is missing or was replaced; preserving guest state' >&2
            return 1
        }
        current_policy_hash=$(sha256sum "$policy_path")
        current_policy_hash=${current_policy_hash%% *}
        [[ "$current_policy_hash" == "$policy_hash" ]] || {
            echo 'created policy-rc.d changed; preserving guest state' >&2
            return 1
        }
        rm -f -- "$policy_path"
        policy_owned=0
    fi
}
cleanup_policy() {
    status=$?
    trap - EXIT HUP INT TERM
    if ! remove_policy; then status=1; fi
    exit "$status"
}
[[ ! -e "$policy_path" && ! -L "$policy_path" ]] || {
    echo 'refusing an unexpected existing /usr/sbin/policy-rc.d' >&2
    exit 1
}
trap cleanup_policy EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM
printf '%s' "$policy_contents" > "$policy_path"
chmod 755 "$policy_path"
apt-get "${apt_options[@]}" install --no-download --no-install-recommends --no-remove --yes "${packages[@]}"
remove_policy
trap - EXIT HUP INT TERM
command -v systemctl >/dev/null 2>&1 || { echo 'systemctl is unavailable; refusing to continue before the CA-only barrier' >&2; exit 1; }
systemctl show-environment >/dev/null 2>&1 || { echo 'system manager is unavailable; refusing to leave stock services unchecked' >&2; exit 1; }
for unit in named.service nginx.service bind9.service; do
    if systemctl cat "$unit" >/dev/null 2>&1; then
        # Debian's bind9.service is an alias. Disabling named can unlink it;
        # stop before removing any installation aliases.
        systemctl stop "$unit"
        systemctl disable "$unit"
        if systemctl is-active --quiet "$unit"; then
            echo "refusing to continue while $unit remains active" >&2
            exit 1
        fi
    fi
done
printf 'dorothy-offline-deps-installed-v1\n%s\n' "$expected" > "$repository/.installed"
chmod 600 "$repository/.installed"
printf 'Installed the pinned Debian 13 package closure from the local repository; stock DNS/web services are disabled.\n'
REMOTE
)
printf -v quoted_remote_program '%q' "$remote_program"
remote_command="bash -c $quoted_remote_program -- $expected_sums"
for package in "${packages[@]}"; do
    printf -v quoted_package '%q' "$package"
    remote_command+=" $quoted_package"
done
target="$SSH_USER@$SSH_HOST"

set -o pipefail
tar --create --file - --directory "$bundle" repo manifest.tsv SHA256SUMS \
    | /usr/bin/ssh -T -F "$SSH_CONFIG" -p "$SSH_PORT" "$target" "$remote_command"
